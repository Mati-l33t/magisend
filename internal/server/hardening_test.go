// A symlink substituted for the resumable upload blob must fail closed and
// never truncate or write the victim file.
func TestUploadSymlinkSubstitutionRejected(t *testing.T) {
	a := testApp(t)
	setupAdmin(t, a)
	token := login(t, a, "mati")
	sh := createShare(t, a, token, "", 6)
	id := sh.Files[0].ID
	if w := chunk(a, token, id, 0, "abc"); w.Code != 200 {
		t.Fatal(w.Code, w.Body)
	}
	victim := filepath.Join(a.root, "victim.bin")
	if e := os.WriteFile(victim, []byte("0123456789"), 0600); e != nil {
		t.Fatal(e)
	}
	if e := os.Remove(a.blob(id)); e != nil {
		t.Fatal(e)
	}
	if e := os.Symlink(victim, a.blob(id)); e != nil {
		t.Fatal(e)
	}
	w := chunk(a, token, id, 3, "XYZ")
	if w.Code != 503 {
		t.Fatalf("substituted upload path answered: %d %s", w.Code, w.Body)
	}
	data, e := os.ReadFile(victim)
	if e != nil || string(data) != "0123456789" {
		t.Fatalf("victim file was truncated or written through the upload path: %q %v", string(data), e)
	}
	var offset int64
	if e := a.db.QueryRow("SELECT offset FROM files WHERE id=?", id).Scan(&offset); e != nil || offset != 3 {
		t.Fatalf("offset advanced on a rejected substitution: %d %v", offset, e)
	}
	if info, e := os.Lstat(a.blob(id)); e != nil || info.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("rejected request replaced the storage object: %v %v", info, e)
	}
}

// The resumable upload handler must open the storage object with O_NOFOLLOW and O_NONBLOCK so a
// symlink/FIFO substituted between path validation and open can neither be
// followed (truncating an unrelated regular file) nor block the mutex. This is
// source-level because the Lstat→OpenFile window cannot be reached from HTTP
// deterministically without a production seam.
func TestUploadOpenNoFollowInvariant(t *testing.T) {
	src, e := os.ReadFile("shares.go")
	if e != nil {
		t.Fatal(e)
	}
	start := strings.Index(string(src), "func (a *App) writeChunk(")
	if start < 0 {
		t.Fatal("upload handler not found")
	}
	body := string(src)[start:]
	if end := strings.Index(body, "\nfunc "); end >= 0 {
		body = body[:end]
	}
	if !strings.Contains(body, "O_NOFOLLOW") {
		t.Fatal("resumable upload must open storage with O_NOFOLLOW; a symlink substituted between validation and open is otherwise followed and truncates an unrelated regular file")
	}
	if !strings.Contains(body, "O_NONBLOCK") {
		t.Fatal("resumable upload must open storage with O_NONBLOCK; a substituted FIFO otherwise blocks the mutex-held request thread")
	}
}

// After lazy generation finishes, the public thumbnail handler must
// re-authorize the share and re-check exact live-folder membership before
// serving the newly generated bytes. Synchronization is deterministic: the
// publish-time worker is allowed to settle first, the row is removed so the
// request must take the lazy path (signal: thumbInflight), membership is
// revoked while the request waits, and lazy generation then succeeds from the
// intact blob. No sleep decides the outcome; the 100ms thumbnail poll step
// simply guarantees both operations have committed before any serving read.
func TestLazyThumbnailRechecksMembership(t *testing.T) {
	a := testApp(t)
	setupAdmin(t, a)
	owner := login(t, a, "mati")
	fid := folderCall(t, a, owner, "POST", "/api/folders", `{"name":"Thumbs"}`, 201)["id"].(string)
	png := pngFixture(t, 8, 8)
	file := libraryUpload(t, a, owner, fid, "pic.png", string(png)).Files[0].ID
	sid := folderCall(t, a, owner, "POST", "/api/library/shares", `{"folder_id":"`+fid+`"}`, 201)["id"].(string)
	// Let the publish-time worker finish on this file (single queued item), so
	// no background write races the fixture below.
	settle := time.Now().Add(10 * time.Second)
	a.mu.Lock()
	for !a.hasThumbnail(file) && time.Now().Before(settle) {
		a.mu.Unlock()
		time.Sleep(2 * time.Millisecond)
		a.mu.Lock()
	}
	a.mu.Unlock()
	if _, e := a.db.Exec("DELETE FROM thumbnails WHERE file_id=?", file); e != nil {
		t.Fatal(e)
	}
	a.thumbBlocked.Delete(file)
	done := make(chan int, 1)
	go func() { done <- call(a, "GET", "/api/public/"+sid+"/files/"+file+"/thumbnail", "", "").Code }()
	inflight := time.Now().Add(10 * time.Second)
	for {
		if _, busy := a.thumbInflight.Load(file); busy {
			break
		}
		if time.Now().After(inflight) {
			t.Fatal("request never reached the lazy thumbnail path")
		}
		time.Sleep(time.Millisecond)
	}
	// The request is waiting for generation. Revoke live membership now; lazy
	// generation still succeeds from the intact blob. A re-checking
	// implementation must refuse to serve the freshly generated bytes.
	if w := call(a, "PATCH", "/api/library/files/"+file, `{"folder_id":""}`, owner); w.Code != 200 {
		t.Fatalf("membership removal: %d %s", w.Code, w.Body)
	}
	if code := <-done; code != 404 {
		t.Fatalf("lazy thumbnail served newly generated bytes after live membership was revoked: %d (want 404)", code)
	}
}

// Text edit and restore go through saveText, which must enforce the
// configured per-file policy limit exactly like upload creation does.
func TestTextEditRespectsPolicyMaxFile(t *testing.T) {
	a := testApp(t)
	setupAdmin(t, a)
	token := login(t, a, "mati")
	if w := call(a, "PUT", "/api/admin/policy", `{"registration_open":false,"default_quota":1073741824,"max_file":1024,"max_share":2147483648,"default_days":7}`, token); w.Code != 200 {
		t.Fatal(w.Code, w.Body)
	}
	folderCall(t, a, token, "PUT", "/api/admin/capabilities/defaults", `{"edit_own":true}`, 200)
	sh := libraryUpload(t, a, token, "", "notes.txt", "a")
	file := sh.Files[0].ID
	big := strings.Repeat("x", 2048)
	w := call(a, "PUT", "/api/library/files/"+file+"/text", textBody(1, big), token)
	if w.Code != 413 {
		t.Fatalf("edit beyond policy max_file accepted: %d %s", w.Code, w.Body)
	}
	if !strings.Contains(w.Body.String(), "invalid_file") {
		t.Fatalf("unexpected error for policy-limited edit: %s", w.Body)
	}
	var size int64
	if e := a.db.QueryRow("SELECT size FROM files WHERE id=?", file).Scan(&size); e != nil || size != 1 {
		t.Fatalf("oversized edit was committed: %d %v", size, e)
	}
	var versions int
	if e := a.db.QueryRow("SELECT COUNT(*) FROM text_versions WHERE file_id=?", file).Scan(&versions); e != nil || versions != 1 {
		t.Fatalf("history was written for the rejected edit: %d %v", versions, e)
	}
	// Control: the same policy is in force and rejects a new upload of that size.
	if w := call(a, "POST", "/api/library/uploads", `{"files":[{"name":"toobig.txt","size":2048}]}`, token); w.Code != 400 {
		t.Fatalf("policy max_file not in force for uploads: %d %s", w.Code, w.Body)
	}
	// Restore must satisfy the same limit: restoring version 1 (1 byte) is legal.
	folderCall(t, a, token, "POST", "/api/library/files/"+file+"/restore", `{"version":1,"restore":1}`, 200)
}

// Deleting the last file of a private library container must release the
// container's metadata reservation, without ever deleting live or selection
// links that merely became empty.
func TestEmptyPrivateContainersGarbageCollected(t *testing.T) {
	a := testApp(t)
	setupAdmin(t, a)
	token := login(t, a, "mati")
	folderCall(t, a, token, "PUT", "/api/admin/capabilities/defaults", `{"edit_own":true}`, 200)
	resetCreateLimit := func() {
		a.mu.Lock()
		for k := range a.attempts {
			delete(a.attempts, k)
		}
		a.mu.Unlock()
	}
	for i := 0; i < 100; i++ {
		resetCreateLimit()
		sh := libraryUpload(t, a, token, "", "loop.txt", "x")
		if w := call(a, "DELETE", "/api/library/files/"+sh.Files[0].ID, `{}`, token); w.Code != 200 {
			t.Fatalf("delete batch %d: %d %s", i, w.Code, w.Body)
		}
		if w := call(a, "DELETE", "/api/trash/"+sh.Files[0].ID, `{}`, token); w.Code != 200 {
			t.Fatalf("empty trash %d: %d %s", i, w.Code, w.Body)
		}
		resetCreateLimit()
	}
	var hidden int
	if e := a.db.QueryRow(`SELECT COUNT(*) FROM shares s JOIN library_containers c ON c.share_id=s.id WHERE NOT EXISTS(SELECT 1 FROM files f WHERE f.share_id=s.id)`).Scan(&hidden); e != nil {
		t.Fatal(e)
	}
	if hidden != 0 {
		t.Fatalf("empty private containers keep share/file metadata parked forever: %d hidden containers", hidden)
	}
	var ownerShares int
	if e := a.db.QueryRow(`SELECT COUNT(*) FROM shares WHERE owner=(SELECT id FROM users WHERE username='mati')`).Scan(&ownerShares); e != nil {
		t.Fatal(e)
	}
	if ownerShares >= 100 {
		t.Fatalf("owner share budget still consumed by empty containers: %d", ownerShares)
	}
	me := folderCall(t, a, token, "GET", "/api/me", "", 200)
	if me["user"].(map[string]any)["used"] != float64(0) {
		t.Fatal(me)
	}
	// Every deleted batch must have released its reservation: a new upload and
	// a new share link still succeed at the same limits.
	sh := libraryUpload(t, a, token, "", "after.txt", "x")
	// An emptied live link is user-visible state and must survive the garbage
	// collection of private containers.
	fid := folderCall(t, a, token, "POST", "/api/folders", `{"name":"LiveGC"}`, 201)["id"].(string)
	if w := call(a, "PATCH", "/api/library/files/"+sh.Files[0].ID, `{"folder_id":"`+fid+`"}`, token); w.Code != 200 {
		t.Fatalf("move into folder: %d %s", w.Code, w.Body)
	}
	sid := folderCall(t, a, token, "POST", "/api/library/shares", `{"folder_id":"`+fid+`"}`, 201)["id"].(string)
	if w := call(a, "DELETE", "/api/library/files/"+sh.Files[0].ID, `{}`, token); w.Code != 200 {
		t.Fatalf("delete of live member: %d %s", w.Code, w.Body)
	}
	if w := call(a, "DELETE", "/api/trash/"+sh.Files[0].ID, `{}`, token); w.Code != 200 {
		t.Fatalf("empty trash: %d %s", w.Code, w.Body)
	}
	w := call(a, "GET", "/api/shares", "", token)
	if w.Code != 200 {
		t.Fatal(w.Code)
	}
	var shares []Share
	if e := json.Unmarshal(w.Body.Bytes(), &shares); e != nil {
		t.Fatal(e)
	}
	found := false
	for _, s := range shares {
		if s.ID == sid {
			found = true
		}
	}
	if !found {
		t.Fatal("the emptied live sharing link was garbage collected together with private containers")
	}
	var links int
	if e := a.db.QueryRow("SELECT COUNT(*) FROM library_shares").Scan(&links); e != nil || links != 1 {
		t.Fatalf("visible link rows lost: %d %v", links, e)
	}
}

// Publishing an already-published share must be idempotent and storage
// validation must verify the current text version, never the original blob and
// never zero-byte creation logic for a versioned member.
func TestPublishValidatesCurrentTextBlob(t *testing.T) {
	a := testApp(t)
	setupAdmin(t, a)
	token := login(t, a, "mati")
	folderCall(t, a, token, "PUT", "/api/admin/capabilities/defaults", `{"edit_own":true}`, 200)
	sh := libraryUpload(t, a, token, "", "notes.txt", "old")
	file := sh.Files[0].ID
	folderCall(t, a, token, "PUT", "/api/library/files/"+file+"/text", textBody(1, "newer"), 200)
	w := call(a, "POST", "/api/shares/"+sh.ID+"/publish", `{}`, token)
	if w.Code != 200 {
		t.Fatalf("container republish after length change: %d %s", w.Code, w.Body)
	}
	sid := folderCall(t, a, token, "POST", "/api/library/shares", `{"files":["`+file+`"]}`, 201)["id"].(string)
	if w = call(a, "POST", "/api/shares/"+sid+"/publish", `{}`, token); w.Code != 200 {
		t.Fatalf("selection link publish after length change: %d %s", w.Code, w.Body)
	}
	folderCall(t, a, token, "PUT", "/api/library/files/"+file+"/text", textBody(2, ""), 200)
	if w = call(a, "POST", "/api/shares/"+sh.ID+"/publish", `{}`, token); w.Code != 200 {
		t.Fatalf("republish with zero-length current text: %d %s", w.Code, w.Body)
	}
	// Idempotent republication must not mutate the original bytes either way.
	if info, e := os.Lstat(a.blob(file)); e != nil {
		t.Fatal(e)
	} else if info.Size() != 3 {
		t.Fatalf("publication rewrote the original blob: %d bytes", info.Size())
	}
}

// L3: selection and live ZIP archives must give every member a unique entry
// name (deterministic and extension-preserving) even when several files share
// the same current filename; extraction must not lose any file.
func TestZipEntryNamesAreUnique(t *testing.T) {
	a := testApp(t)
	setupAdmin(t, a)
	token := login(t, a, "mati")
	first := libraryUpload(t, a, token, "", "notes.txt", "AAA")
	second := libraryUpload(t, a, token, "", "notes.txt", "BBB")
	check := func(sid, scope string) {
		t.Helper()
		w := call(a, "GET", "/api/public/"+sid+"/zip", "", "")
		if w.Code != 200 {
			t.Fatalf("%s zip: %d %s", scope, w.Code, w.Body)
		}
		z, e := zip.NewReader(bytes.NewReader(w.Body.Bytes()), int64(w.Body.Len()))
		if e != nil {
			t.Fatalf("%s zip unreadable: %v", scope, e)
		}
		if len(z.File) != 2 {
			t.Fatalf("%s zip lost a member: %d entries", scope, len(z.File))
		}
		names := map[string]string{}
		for _, f := range z.File {
			if _, dup := names[f.Name]; dup {
				t.Fatalf("%s zip contains duplicate entry %q; extraction overwrites one file", scope, f.Name)
			}
			if !strings.HasSuffix(f.Name, ".txt") {
				t.Fatalf("%s zip entry %q lost the file extension", scope, f.Name)
			}
			r, e := f.Open()
			if e != nil {
				t.Fatal(e)
			}
			data, _ := io.ReadAll(r)
			r.Close()
			names[f.Name] = string(data)
		}
		contents := map[string]bool{}
		for _, v := range names {
			contents[v] = true
		}
		if !contents["AAA"] || !contents["BBB"] {
			t.Fatalf("%s zip member contents lost: %v", scope, names)
		}
	}
	sid := folderCall(t, a, token, "POST", "/api/library/shares", `{"files":["`+first.Files[0].ID+`","`+second.Files[0].ID+`"]}`, 201)["id"].(string)
	check(sid, "selection")
	fid := folderCall(t, a, token, "POST", "/api/folders", `{"name":"Dup"}`, 201)["id"].(string)
	if w := call(a, "PATCH", "/api/library/files/"+first.Files[0].ID, `{"folder_id":"`+fid+`"}`, token); w.Code != 200 {
		t.Fatalf("move first: %d %s", w.Code, w.Body)
	}
	if w := call(a, "PATCH", "/api/library/files/"+second.Files[0].ID, `{"folder_id":"`+fid+`"}`, token); w.Code != 200 {
		t.Fatalf("move second: %d %s", w.Code, w.Body)
	}
	live := folderCall(t, a, token, "POST", "/api/library/shares", `{"folder_id":"`+fid+`"}`, 201)["id"].(string)
	check(live, "live")
}
